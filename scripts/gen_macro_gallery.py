#!/usr/bin/env python3
"""Regenerate ``ComplexAnalysisCourse/MacroGallery.lean`` from ``ComplexAnalysisCourse/Macros.lean``.

The gallery is a Verso document that uses every math macro once. It is part of the ``lean_lib`` (so every
``lake build`` lints all macros with KaTeX) but is *not* included in the published site.  A macro that
KaTeX rejects shows up as ``KaTeX rejected blueprint math`` in the build log.

Usage: python3 scripts/gen_macro_gallery.py            (run after editing Macros.lean)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MACROS = ROOT / "ComplexAnalysisCourse" / "Macros.lean"
GALLERY = ROOT / "ComplexAnalysisCourse" / "MacroGallery.lean"

DEF_RE = re.compile(
    r"\\(?:newcommand|renewcommand|providecommand)\{\\([A-Za-z]+)\}(?:\[(\d)\])?"
    r"|\\(?:def|gdef)\\([A-Za-z]+)((?:#\d)*)")


def macros_of(text):
    """(name, arity) for every macro defined inside a ``tex_prelude`` raw string."""
    out = []
    for chunk in re.findall(r'r#"(.*?)"#', text, re.S):
        for m in DEF_RE.finditer(chunk):
            if m.group(1):
                out.append((m.group(1), int(m.group(2) or 0)))
            else:
                out.append((m.group(3), len(re.findall(r"#\d", m.group(4)))))
    return out


def main():
    macros = macros_of(MACROS.read_text(encoding="utf8"))
    if not macros:
        sys.exit("no macros found in Macros.lean")
    lines = [
        "import Verso", "import VersoManual", "import VersoBlueprint",
        "import ComplexAnalysisCourse.Macros", "",
        "open Verso.Genre", "open Verso.Genre.Manual", "open Informal", "",
        "/-!",
        "GENERATED by `scripts/gen_macro_gallery.py` from `Macros.lean` - do not edit.",
        "Uses every macro once, so that `lake build` lints them with KaTeX. Not part of the published site.",
        "-/", "",
        '#doc (Manual) "Macro gallery" =>', "",
    ]
    for name, arity in macros:
        args = "".join("{x_%d}" % (k + 1) for k in range(arity))
        lines.append(f"`\\{name}` renders as $`\\{name}{args}`.\n")
    GALLERY.write_text("\n".join(lines), encoding="utf8")
    print(f"{len(macros)} macros -> {GALLERY.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
